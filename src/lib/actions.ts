type ChangePasswordState = { success: boolean; error: boolean; message?: string };

export const changePassword = async (
  currentState: ChangePasswordState,
  formData: FormData
): Promise<ChangePasswordState> => {
  const session = await auth();
  if (!session?.user?.id || !session.user.role) {
    return { success: false, error: true, message: "Not signed in." };
  }

  const currentPassword = formData.get("currentPassword") as string;
  const newPassword = formData.get("newPassword") as string;
  const confirmPassword = formData.get("confirmPassword") as string;

  if (!currentPassword || !newPassword) {
    return { success: false, error: true, message: "All fields are required." };
  }
  if (newPassword.length < 8) {
    return {
      success: false,
      error: true,
      message: "New password must be at least 8 characters long.",
    };
  }
  if (newPassword !== confirmPassword) {
    return { success: false, error: true, message: "New passwords do not match." };
  }

  const { id, role } = session.user;

  try {
    let currentHash: string | undefined;

    switch (role) {
      case "admin":
        currentHash = (await prisma.admin.findUnique({ where: { id } }))
          ?.password;
        break;
      case "teacher":
        currentHash = (await prisma.teacher.findUnique({ where: { id } }))
          ?.password;
        break;
      case "student":
        currentHash = (await prisma.student.findUnique({ where: { id } }))
          ?.password;
        break;
      case "parent":
        currentHash = (await prisma.parent.findUnique({ where: { id } }))
          ?.password;
        break;
    }

    if (!currentHash) {
      return { success: false, error: true, message: "User not found." };
    }

    const valid = await bcrypt.compare(currentPassword, currentHash);
    if (!valid) {
      return { success: false, error: true, message: "Current password is incorrect." };
    }

    const hashedNewPassword = await bcrypt.hash(newPassword, 10);

    switch (role) {
      case "admin":
        await prisma.admin.update({ where: { id }, data: { password: hashedNewPassword } });
        break;
      case "teacher":
        await prisma.teacher.update({ where: { id }, data: { password: hashedNewPassword } });
        break;
      case "student":
        await prisma.student.update({ where: { id }, data: { password: hashedNewPassword } });
        break;
      case "parent":
        await prisma.parent.update({ where: { id }, data: { password: hashedNewPassword } });
        break;
    }

    return { success: true, error: false, message: "Password updated successfully." };
  } catch (err) {
    console.log(err);
    return { success: false, error: true, message: "Something went wrong." };
  }
};
